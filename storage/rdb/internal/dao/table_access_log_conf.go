const tAccessLogConfTableName = "access_log_conf"

// accessLogConfFixedID is the fixed primary key of the singleton row
// (single-row overwrite storage; see design-docs/sys-design/数据库设计文档.md
// section 6.12).
const accessLogConfFixedID = int64(1)

const (
	tAccessLogConfUpsertMySQL = "INSERT INTO access_log_conf (id, req_headers, res_headers) " +
		"VALUES (?, ?, ?) " +
		"ON DUPLICATE KEY UPDATE req_headers = VALUES(req_headers), res_headers = VALUES(res_headers)"
	tAccessLogConfInsertSQLite = "INSERT OR IGNORE INTO access_log_conf (id, req_headers, res_headers) VALUES (?, ?, ?)"
	tAccessLogConfUpdateSQLite = "UPDATE access_log_conf SET req_headers = ?, res_headers = ? WHERE id = ?"
)

// TAccessLogConf maps to access_log_conf table (single-row singleton,
// fixed id=1; no version column: the distribution version is the data
// signature generated by the export pipeline, see iversion_control).
type TAccessLogConf struct {
	Id         int64     `db:"id"`
	ReqHeaders string    `db:"req_headers"`
	ResHeaders string    `db:"res_headers"`
	CreatedAt  time.Time `db:"created_at"`
	UpdatedAt  time.Time `db:"updated_at"`
}

// TAccessLogConfOne Query One
// return nil, nil if record not existed
func TAccessLogConfOne(dbCtx lib.DBContexter, where *TAccessLogConfParam) (*TAccessLogConf, error) {
	t := &TAccessLogConf{}
	err := internal.QueryOne(dbCtx, tAccessLogConfTableName, where, t)
	if err == nil {
		return t, nil
	}
	if xerror.Cause(err) == internal.ErrRecordNotFound {
		return nil, nil
	}
	return nil, err
}

type TAccessLogConfParam struct {
	Id         *int64     `db:"id"`
	ReqHeaders *string    `db:"req_headers"`
	ResHeaders *string    `db:"res_headers"`
	CreatedAt  *time.Time `db:"created_at"`
	UpdatedAt  *time.Time `db:"updated_at"`

	OrderBy *string `db:"_orderby"`
}

// TAccessLogConfCreate One
func TAccessLogConfCreate(dbCtx lib.DBContexter, data *TAccessLogConfParam) (int64, error) {
	if data.CreatedAt == nil {
		data.CreatedAt = internal.PTimeNow()
	}
	return internal.Create(dbCtx, tAccessLogConfTableName, data)
}

// TAccessLogConfUpdate Update One
func TAccessLogConfUpdate(dbCtx lib.DBContexter, val, where *TAccessLogConfParam) (int64, error) {
	return internal.Update(dbCtx, tAccessLogConfTableName, where, val)
}

// TAccessLogConfUpsert overwrites the singleton row (fixed id=1): insert
// when absent, overwrite when present. It handles both dialects (same
// pattern as TIntentConfigUpsert):
//   - MySQL: INSERT ... ON DUPLICATE KEY UPDATE in one statement; updated_at
//     is maintained by ON UPDATE CURRENT_TIMESTAMP.
//   - SQLite: INSERT OR IGNORE followed by UPDATE (idempotent overwrite); the
//     updated_at trigger maintains the timestamp.
func TAccessLogConfUpsert(dbCtx lib.DBContexter, data *TAccessLogConfParam) error {
	if isMySQL(dbCtx.Conn()) {
		return upsertAccessLogConfMySQL(dbCtx, data)
	}
	return upsertAccessLogConfSQLite(dbCtx, data)
}

func upsertAccessLogConfMySQL(dbCtx lib.DBContexter, data *TAccessLogConfParam) error {
	_, err := dbCtx.Execer().ExecContext(dbCtx,
		tAccessLogConfUpsertMySQL,
		accessLogConfFixedID, data.ReqHeaders, data.ResHeaders)
	return err
}

func upsertAccessLogConfSQLite(dbCtx lib.DBContexter, data *TAccessLogConfParam) error {
	if _, err := dbCtx.Execer().ExecContext(dbCtx,
		tAccessLogConfInsertSQLite,
		accessLogConfFixedID, data.ReqHeaders, data.ResHeaders); err != nil {
		return err
	}

	_, err := dbCtx.Execer().ExecContext(dbCtx,
		tAccessLogConfUpdateSQLite,
		data.ReqHeaders, data.ResHeaders, accessLogConfFixedID)
	return err
}
